export const messages: Record<Lang, Record<PlatformKey, string>> = { en, ar };

export type PT = (
	key: PlatformKey,
	params?: Record<string, string | number>,
) => string;

export function platformT(lang: Lang): PT {
	const dict = messages[lang];
	return (key, params) =>
		params
			? dict[key].replace(/\{(\w+)\}/g, (m, n: string) =>
					n in params ? String(params[n]) : m,
				)
			: dict[key];
}
